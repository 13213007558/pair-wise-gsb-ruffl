#
# Field_isomorphism
#
# The same abstract field F_{2^m} may appear in two data sets through
# two different irreducible moduli p1 and p2:
#
#   E1 = F_2[x]/(p1)   and   E2 = F_2[x]/(p2)
#
# Although E1 and E2 are isomorphic, their bit representations are not
# directly interchangeable: the residue 1+x (say) means "1+x mod p1"
# in one file and "1+x mod p2" in the other.  Copying bit patterns
# across is in general not even a ring homomorphism, because x mod p2
# usually fails to be a root of p1.
#
# An isomorphism phi: E1 -> E2 is fixed once we choose the image of the
# source generator x.  That image must be a root beta of p1 inside E2
# (so that the relation p1(x) = 0 maps to p1(beta) = 0), and conversely
# any such root determines a valid isomorphism by
#
#   phi(a_0 + a_1 x + ... + a_{m-1} x^{m-1})
#     = a_0 + a_1 beta + ... + a_{m-1} beta^{m-1}   (mod p2).
#
# The choice is NOT unique: p1 has exactly m distinct roots in F_{2^m}
# (the field is Galois over F_2, so p1 splits completely in it), namely
# the Frobenius orbit beta, beta^2, beta^4, ..., beta^{2^{m-1}}.  Each
# root yields a different isomorphism, and the m choices differ by the
# m automorphisms of the target field (Gal(F_{2^m}/F_2) is cyclic of
# order m, generated by the Frobenius map a -> a^2).  The choice is
# unique only when m = 1.
#
# Because of this non-uniqueness, the image of the source generator may
# be supplied explicitly.  If it is omitted, a stable rule is used: all
# roots of p1 in E2 are enumerated in increasing integer (bit-pattern)
# order -- the same "lexically lowest" convention as
# F2_poly_factor.lowest_irr -- and the lowest root is taken.  The
# rationale string records which root was chosen and why, so any
# conversion can be audited and reproduced.
#
# Inputs are rejected (ArgumentError) when
#   * the two moduli have different degrees (the fields differ), or
#   * either modulus is not irreducible (the quotient is not a field),
#   * an explicitly supplied image is not a root of p1 in E2.
# ================================================================

require 'F2_poly.rb'
require 'F2_poly_mod.rb'
require 'F2_poly_factor.rb'

class Field_isomorphism
	# ----------------------------------------------------------------
	# source_modulus, target_modulus: irreducible F2_poly's of the same
	# degree m.  image_of_generator (optional): residue, modulo the
	# target modulus, of the source generator x; it must be a root of
	# the source modulus in the target field.  If nil, the lexically
	# lowest root is chosen automatically (see the header comment).
	def initialize(source_modulus, target_modulus, image_of_generator = nil)
		@source_modulus = Field_isomorphism.to_f2poly(source_modulus)
		@target_modulus = Field_isomorphism.to_f2poly(target_modulus)

		source_degree = @source_modulus.degree
		target_degree = @target_modulus.degree
		if source_degree != target_degree
			raise ArgumentError, "Field_isomorphism: degree mismatch: " \
				"source modulus #{@source_modulus} has degree #{source_degree}; " \
				"target modulus #{@target_modulus} has degree #{target_degree}."
		end
		if !F2_poly_factor.irr?(@source_modulus)
			raise ArgumentError, "Field_isomorphism: source modulus " \
				"#{@source_modulus} is not irreducible over F_2."
		end
		if !F2_poly_factor.irr?(@target_modulus)
			raise ArgumentError, "Field_isomorphism: target modulus " \
				"#{@target_modulus} is not irreducible over F_2."
		end

		# F_{2^m} contains all m roots of the source modulus, so this
		# is guaranteed to find them.
		@roots = find_roots

		if image_of_generator.nil?
			@image_of_generator = @roots[0]
			@rationale = "auto: chose lexically lowest root " \
				"#{@image_of_generator} of source modulus #{@source_modulus} " \
				"in the target field mod #{@target_modulus}, out of " \
				"#{@roots.length} root(s): #{@roots.join(' ')}."
		else
			image = Field_isomorphism.to_f2poly(image_of_generator) %
				@target_modulus
			if !root?(image)
				raise ArgumentError, "Field_isomorphism: proposed image " \
					"#{image} of the source generator is not a root of " \
					"#{@source_modulus} modulo #{@target_modulus}."
			end
			@image_of_generator = image
			@rationale = "explicit: image #{@image_of_generator} of the " \
				"source generator was supplied by the caller and verified " \
				"to be a root of #{@source_modulus} modulo #{@target_modulus}."
		end
	end

	attr_reader :source_modulus, :target_modulus
	attr_reader :image_of_generator, :roots, :rationale

	# ----------------------------------------------------------------
	def to_s
		"F_2[x]/(#{@source_modulus}) -> F_2[x]/(#{@target_modulus}), " \
			"x -> #{@image_of_generator}"
	end

	# ----------------------------------------------------------------
	# Map a source-field element into the target field.  The argument
	# may be an F2_poly_mod over the source modulus, or an F2_poly /
	# integer residue (reduced mod the source modulus first).  The bit
	# pattern is NOT copied across; the residue is re-expressed as a
	# polynomial in the image of the source generator.
	def convert(element)
		if F2_poly_mod === element
			if element.modulus != @source_modulus
				raise ArgumentError, "Field_isomorphism.convert: element " \
					"#{element.inspect} is not in the source field."
			end
			residue = element.residue
		else
			residue = Field_isomorphism.to_f2poly(element) % @source_modulus
		end
		return evaluate_in_target(residue, @image_of_generator)
	end

	# ----------------------------------------------------------------
	# The inverse isomorphism E2 -> E1.  The image of the target
	# generator y is the unique source element mapping to y; it is
	# found by a deterministic scan in increasing bit-pattern order.
	def inverse
		target_generator = F2_poly_mod.new(2, @target_modulus)
		m = @source_modulus.degree
		for bits in 0..((1 << m) - 1)
			preimage = F2_poly.new(bits)
			if convert(preimage) == target_generator
				return Field_isomorphism.new(
					@target_modulus, @source_modulus, preimage)
			end
		end
		# convert is a bijection, so a preimage always exists.
		raise "Field_isomorphism.inverse: coding error detected."
	end

	# ----------------------------------------------------------------
	def Field_isomorphism.to_f2poly(arg)
		if F2_poly_mod === arg
			return arg.residue
		elsif F2_poly === arg
			return arg
		else # Nominally expecting integer or quacks-like-integer.
			return F2_poly.new(arg)
		end
	end

	private

	# ----------------------------------------------------------------
	# All roots of the source modulus in the target field, in increasing
	# integer (bit-pattern) order.
	def find_roots
		m = @target_modulus.degree
		found = []
		for bits in 0..((1 << m) - 1)
			candidate = F2_poly.new(bits)
			found.push(candidate) if root?(candidate)
		end
		return found
	end

	def root?(candidate)
		evaluate_in_target(@source_modulus, candidate).zero?
	end

	# Horner evaluation of poly (a polynomial over F_2) at the
	# target-field element whose residue is point; all arithmetic is
	# done modulo the target modulus.
	def evaluate_in_target(poly, point)
		acc = F2_poly_mod.new(0, @target_modulus)
		xp  = F2_poly_mod.new(point, @target_modulus)
		poly.degree.downto(0) do |i|
			acc *= xp
			if poly[i] == 1
				acc += F2_poly_mod.new(1, @target_modulus)
			end
		end
		return acc
	end

end
